/**
 * Varied Hebrew news-article generator.
 *
 * Produces a distinct summary + multi-paragraph body per article, themed by the
 * headline keywords and category, with a per-article seed so output is varied yet
 * reproducible. Shared by the seeder (seeders/content.php) and the repair script
 * (fix_news_content.php) so both stay in sync.
 */

if (!function_exists('news_seeded_pick')) {
    /** Deterministically pick $n distinct items from $pool using mt_rand (seed set by caller). */
    function news_seeded_pick(array $pool, int $n): array
    {
        $pool = array_values($pool);
        $count = count($pool);
        if ($n >= $count) { return $pool; }
        $keys = array_keys($pool);
        // Fisher-Yates partial shuffle driven by the already-seeded RNG.
        for ($i = 0; $i < $n; $i++) {
            $j = $i + (mt_rand() % ($count - $i));
            [$keys[$i], $keys[$j]] = [$keys[$j], $keys[$i]];
        }
        $out = [];
        for ($i = 0; $i < $n; $i++) { $out[] = $pool[$keys[$i]]; }
        return $out;
    }
}

if (!function_exists('news_theme')) {
    /** Detect a coarse theme from headline keywords. */
    function news_theme(string $title): string
    {
        $map = [
            'אינפלציה' => 'inflation', 'הריבית' => 'rates', 'ריבית' => 'rates',
            'הפד' => 'fed', 'פדרל' => 'fed', 'הטכנולוגיה' => 'tech', 'AI' => 'ai',
            'בינה' => 'ai', 'מוליכים' => 'semis', 'הונג קונג' => 'hk', 'סין' => 'china',
            'הזהב' => 'gold', 'הנפט' => 'oil', 'הרכב החשמלי' => 'ev', 'דיבידנד' => 'dividend',
            'הקריפטו' => 'crypto', 'אג"ח' => 'bonds', 'התעסוקה' => 'jobs', 'IPO' => 'ipo',
            'הרבעון' => 'earnings', 'יעד' => 'targets', 'תמריצים' => 'stimulus',
        ];
        foreach ($map as $kw => $theme) {
            if (mb_strpos($title, $kw) !== false) { return $theme; }
        }
        return 'general';
    }
}

